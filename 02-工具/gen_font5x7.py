FIRST, LAST = 0x20, 0x5A          # ' ' .. 'Z'
BLANK = [".....", ".....", ".....", ".....", ".....", ".....", "....."]


def rows_to_bytes(rows):
    """7 行 x 5 列 -> 7 字节，bit4 = 最左。"""
    out = []
    for r in rows:
        assert len(r) == 5, "行宽必须是 5: %r" % r
        v = 0
        for i, c in enumerate(r):
            assert c in '#.', "只能有 #/. : %r" % r
            if c == '#':
                v |= 1 << (4 - i)     # 最左 -> bit4
        out.append(v)
    return out


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.normpath(os.path.join(
        here, '..', '..', 'claudecode', 'stm32-bc28',
        'eink-demo', 'Project', 'HARDWARE', 'eink', 'font5x7.h'))

    chars = [chr(c) for c in range(FIRST, LAST + 1)]
    table = []
    missing = []

    # ---- 终端预览，肉眼验字 ----
    print("=" * 58)
    print("5x7 glyph preview  (ASCII 0x%02X..0x%02X)" % (FIRST, LAST))
    print("=" * 58)
    for i in range(0, len(chars), 10):
        chunk = chars[i:i + 10]
        for r in range(7):
            line = ""
            for ch in chunk:
                rows = GLYPHS.get(ch, BLANK)
                line += "  " + rows[r].replace('#', '#').replace('.', '.')
            print(line)
        line = ""
        for ch in chunk:
            line += "  %-5s" % ("'%s'" % ch if ch != ' ' else 'SP')
        print(line)
        print("")

    for ch in chars:
        rows = GLYPHS.get(ch)
        if rows is None:
            missing.append(ch)
            rows = BLANK
        table.extend(rows_to_bytes(rows))

    lines = []
    lines.append("#ifndef __FONT5X7_H")
    lines.append("#define __FONT5X7_H")
    lines.append("")
    lines.append("/*")
    lines.append(" * 5x7 ASCII font, ASCII 0x%02X..0x%02X (%d glyphs), 7 bytes each."
                 % (FIRST, LAST, len(chars)))
    lines.append(" * byte r = row r (top -> bottom); bit4 = leftmost pixel; 1 = ink (black).")
    lines.append(" * generated by D:\\windows11-tools\\stm32-bc28\\gen_font5x7.py")
    lines.append(" */")
    lines.append("#define FONT5X7_FIRST 0x%02X" % FIRST)
    lines.append("#define FONT5X7_LAST  0x%02X" % LAST)
    lines.append("#define FONT5X7_W     5")
    lines.append("#define FONT5X7_H     7")
    lines.append("")
    lines.append("const unsigned char FONT5X7[] = {")
    for i in range(0, len(table), 7):
        ch = chars[i // 7]
        hexes = ",".join("0x%02X" % b for b in table[i:i + 7])
        label = "'%s'" % ch if ch != ' ' else "SP "
        lines.append("    %s,  /* %s */" % (hexes, label))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* __FONT5X7_H */")
    lines.append("")

    with open(out_path, 'w') as f:
        f.write("\n".join(lines))

    print("=" * 58)
    print("wrote %s" % out_path)
    print("%d glyphs, %d bytes" % (len(chars), len(table)))
    if missing:
        print("blank (no art defined): %s" % "".join(missing))
    print("=" * 58)


if __name__ == '__main__':
    main()
