/**
  ******************************************************************************
  * @file    HARDWARE/dht11/dht11.h
  * @brief   DHT11 温湿度传感器驱动 —— 自己写的, 不搬厂家 HARDWARE/DHT11。
  *          配套手册: 第 5 篇 · 多路采集与云端看板
  *
  *  接线(板上丝印就是 `+ B8 -`, 左到右):
  *      板子 +   ->  模块 VCC
  *      板子 B8  ->  模块 DATA (丝印可能是 S / DATA / OUT)
  *      板子 -   ->  模块 GND
  *
  *  ⚠ **模块的引脚顺序不一定是 VCC/DATA/GND**, 插之前一定要先认准 ——
  *    插反了就是把 3.3V 打进传感器的数据脚。认法: 3 针模块上的上拉电阻
  *    接在 **DATA 和 VCC 之间**, 所以万用表量"S 与另一脚"的电阻,
  *    哪个是 4.7k~10k, 哪个就是 VCC, 剩下那个是 GND。
  *    板子这侧**没有**上拉电阻(原理图 PB8 网络上没有), 全靠模块自带的那颗。
  *
  *  这个驱动的一个特点: **位的宽度是"量"出来的, 不是"延时后采样"出来的。**
  *  见 dht11.c 开头那段, 那里讲了为什么本工程里只有这一条路可走。
  ******************************************************************************
  */

#ifndef __DHT11_H
#define __DHT11_H

#include "stm32l1xx.h"

/* ---- 返回值 -------------------------------------------------------------
   >= 0 成功; < 0 是下面这些错误码。
   **每一个码都对应一种物理原因**, 不是一个笼统的"失败" —— 手上只有一块板子
   的时候, 错误码就是唯一的诊断手段, 所以这里分得细。 */
#define DHT11_E_ARG     (-1)    /* 调用方参数不对(NULL) */
#define DHT11_E_NORESP  (-2)    /* 起始信号发完了, 线一直没被拉低
                                   -> 传感器没接 / 没上电 / 插错脚 */
#define DHT11_E_STUCK   (-3)    /* 线低下去了再没起来
                                   -> 短路到地 / 上拉电阻没接 / 传感器没供电 */
#define DHT11_E_TIMEOUT (-4)    /* 40 位读到一半超时 -> 时序被干扰, 或供电不稳 */
#define DHT11_E_SUM     (-5)    /* 校验和不对 -> 有位读错(偶尔一次是正常的, 重读) */
#define DHT11_E_RANGE   (-6)    /* 校验过了但数值超量程 -> 位错位, 校验和偶然撞对 */

/* ---- 引脚 ---------------------------------------------------------------
   板上 DHT11 排针的中间那根, 丝印是 `B8`。
   原理图里这个网络的编号叫 STM32_PB8_BS18B20 —— 同一个排针既能插 DHT11
   也能插 DS18B20, 靠固件区分, 硬件上就是一根线。 */
#define DHT11_PORT      GPIOB
#define DHT11_PIN       GPIO_Pin_8

/* ---- 读的节奏 -----------------------------------------------------------
   DHT11 手册要求采样间隔 >= 1 秒; 取 2 秒是留一倍余量。
   这么慢是因为它的敏感元件要"缓"过来 —— 连着读只会拿到同一个数。 */
#define DHT11_MIN_PERIOD_MS     2000

/* ---- 一次读数的结果 ------------------------------------------------------
   前半是"数据", 后半是"这次是怎么测出来的"。

   后面那几个实测值不是调试残留, 是**唯一**能证明"读对了"的东西:
   DHT11 的 0 和 1 只差在高电平宽度(26~28us vs 70us), 门槛取 50us。
   把 hi0_max / hi1_min 打出来, 就知道两边的余量各有多少 ——
   余量小说明线太长/上拉太弱, 现在能读, 换个环境就未必。
   接错线的时候也是靠这几个数一眼看出"时序根本不对, 不是传感器坏"。 */
typedef struct
{
    /* ---- 数据(校验通过才有意义) ---- */
    uint8_t  humi;          /* 湿度整数部分, %RH */
    uint8_t  humi_dec;      /* 湿度小数部分, DHT11 恒为 0 */
    uint8_t  temp;          /* 温度整数部分, 最高位是符号(负温时置 1) */
    uint8_t  temp_dec;      /* 温度小数部分, DHT11 恒为 0 */
    uint8_t  raw[5];        /* 原样 5 个字节, 校验失败时靠它看错在哪 */
    uint8_t  sum_ok;        /* 校验和通过 */

    /* ---- 实测量, 单位都是微秒 ---- */
    uint16_t start_us;      /* 我们拉低了多久(应当 ~20000) */
    uint16_t resp_low;      /* 传感器响应: 低电平宽度(手册 80) */
    uint16_t resp_high;     /* 传感器响应: 高电平宽度(手册 80) */
    uint16_t hi0_max;       /* 40 位里 **判为 0** 的最宽高电平(应当 <=28) */
    uint16_t hi1_min;       /* 40 位里 **判为 1** 的最窄高电平(应当 >=70) */
    uint16_t lo_max;        /* 位与位之间那个低电平的最大宽度(应当 ~50) */
    uint16_t frame_us;      /* 响应头 + 40 位一共花了多久(应当 ~4000) */
} DHT11_DATA;

/* ---- 接口 --------------------------------------------------------------- */
void        DHT11_Init(void);           /* PB8 开漏 + TIM6 微秒时基, 调一次 */
int         DHT11_Read(DHT11_DATA *d);  /* 一次完整读数, 阻塞约 25ms */
const char *DHT11_Why(int rc);          /* 错误码 -> 可以直接打日志的短串 */

#endif /* __DHT11_H */
